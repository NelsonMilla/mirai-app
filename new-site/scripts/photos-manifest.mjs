// Lists the speaker portraits that exist so pages never request a missing one.
// Run after adding or removing files in img/speakers/: npm run photos:manifest
import { readdirSync, writeFileSync } from 'node:fs';
const ids = readdirSync(new URL('../img/speakers/', import.meta.url))
  .filter((f) => f.endsWith('.jpeg')).map((f) => f.slice(0, -5)).sort();
writeFileSync(new URL('../speakers-photos.js', import.meta.url),
  `/* GENERATED by scripts/photos-manifest.mjs — the portraits present in img/speakers/.\n   A blank Photo cell uses /img/speakers/<first_last>.jpeg only when it is listed here. */\nwindow.MIRAI_SPEAKER_PHOTOS = ${JSON.stringify(ids)};\n`);
console.log(`Listed ${ids.length} portraits in speakers-photos.js`);
