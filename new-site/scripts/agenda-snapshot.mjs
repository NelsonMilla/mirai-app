// Refreshes the built-in agenda snapshot from the Google Sheet.
// Usage (from new-site/): npm run agenda:snapshot [-- --file <path>]
// Reads the sheet URL from agenda-data.js, fetches the CSV, rewrites the file.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const KEYS = ['block', 'date', 'blocktitle', 'title', 'subtitle', 'link', 'publish'];
const URL_LINE = /window\.MIRAI_AGENDA_SHEET_CSV = '([^']*)';/;

const fileArg = process.argv.indexOf('--file');
const dataFile = fileArg > -1 && process.argv[fileArg + 1]
  ? process.argv[fileArg + 1]
  : fileURLToPath(new URL('../agenda-data.js', import.meta.url));

/** RFC 4180: quoted fields, "" escapes, embedded newlines, CRLF, BOM. */
function parseCsv(text) {
  text = text.replace(/^\uFEFF/, '');
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ''));
}

const source = readFileSync(dataFile, 'utf8');
const match = source.match(URL_LINE);
if (!match || !match[1]) {
  console.error(`No sheet URL in ${dataFile}. Set window.MIRAI_AGENDA_SHEET_CSV = '<csv url>'; first (see AGENDA.md).`);
  process.exit(1);
}

const res = await fetch(match[1], { cache: 'no-store' });
if (!res.ok) {
  console.error(`Fetching the sheet failed: HTTP ${res.status} from ${match[1]}`);
  process.exit(1);
}
const [header = [], ...body] = parseCsv(await res.text());
const keys = header.map((h) => h.toLowerCase().replace(/\s+/g, ''));
const rows = body.map((cells) => Object.fromEntries(
  KEYS.map((k) => [k, keys.includes(k) ? (cells[keys.indexOf(k)] ?? '') : '']),
));

writeFileSync(dataFile, [
  `// Generated by scripts/agenda-snapshot.mjs on ${new Date().toISOString()} — do not edit by hand; edit the sheet and rerun npm run agenda:snapshot`,
  match[0],
  `window.MIRAI_AGENDA_SNAPSHOT = ${JSON.stringify(rows, null, 2)};`,
  '',
].join('\n'));
console.log(`Wrote ${rows.length} rows to ${dataFile}`);
