// Refreshes a built-in sheet snapshot (agenda or speakers) from the Google Sheet.
// Usage (from new-site/): npm run agenda:snapshot | npm run speakers:snapshot
//   or: node scripts/sheet-snapshot.mjs --file <data file>
// Reads window.MIRAI_<NAME>_SHEET_CSV from the data file, fetches that CSV and
// rewrites the file with window.MIRAI_<NAME>_SNAPSHOT, one object per row keyed
// by the CSV's header names (lowercase, spaces removed).
import { readFileSync, writeFileSync } from 'node:fs';

const URL_LINE = /window\.MIRAI_([A-Z]+)_SHEET_CSV = '([^']*)';/;

const fileArg = process.argv.indexOf('--file');
const dataFile = fileArg > -1 ? process.argv[fileArg + 1] : '';
if (!dataFile) {
  console.error('Usage: node scripts/sheet-snapshot.mjs --file <data file>  (e.g. agenda-data.js, speakers-data.js)');
  process.exit(1);
}

/** RFC 4180: quoted fields, "" escapes, embedded newlines, CRLF, BOM. */
function parseCsv(text) {
  text = text.replace(/^﻿/, '');
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ''));
}

const source = readFileSync(dataFile, 'utf8');
const match = source.match(URL_LINE);
if (!match || !match[2]) {
  console.error(`No sheet URL in ${dataFile}. Set window.MIRAI_<NAME>_SHEET_CSV = '<csv url>'; first (see AGENDA.md).`);
  process.exit(1);
}
const [urlLine, name, url] = match;

const res = await fetch(url, { cache: 'no-store' });
if (!res.ok) {
  console.error(`Fetching the sheet failed: HTTP ${res.status} from ${url}`);
  process.exit(1);
}
const [header = [], ...body] = parseCsv(await res.text());
const keys = header.map((h) => h.toLowerCase().replace(/\s+/g, ''));
// Unnamed columns (gviz can emit empty trailing headers) are dropped.
const rows = body.map((cells) => Object.fromEntries(
  keys.map((k, i) => [k, cells[i] ?? '']).filter(([k]) => k !== ''),
));

const script = `${name.toLowerCase()}:snapshot`;
writeFileSync(dataFile, [
  `// Generated by scripts/sheet-snapshot.mjs on ${new Date().toISOString()} — do not edit by hand; edit the sheet and rerun npm run ${script}`,
  urlLine,
  `window.MIRAI_${name}_SNAPSHOT = ${JSON.stringify(rows, null, 2)};`,
  '',
].join('\n'));
console.log(`Wrote ${rows.length} rows to ${dataFile}`);
